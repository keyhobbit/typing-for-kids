// GetRandomLesson returns a random Lesson for the given level (1–3).
func GetRandomLesson(level int) Lesson {
	if level < 1 { level = 1 }
	if level > 3 { level = 3 }
	items := lessonBank[level]
	return Lesson{Content: items[rand.Intn(len(items))], Level: level}
}
